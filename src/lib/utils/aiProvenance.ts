/**
 * Surfacing AI provenance as an "AI Data Consumer", per the HL7 AI Transparency
 * on FHIR IG (http://hl7.org/fhir/uv/aitransparency).
 *
 * The IG labels AI involvement in several complementary ways, and a consumer has
 * to look at all of them because producers are free to use whichever fit:
 *
 *   Resource level
 *     - Resource.meta.security = v3-ObservationValue#AIAST
 *     - An AI Provenance whose target references the resource with no targetPath
 *     - The AIconfidence extension on the resource root
 *     - The resource pointing at an AI Device (e.g. Observation.device)
 *
 *   Element level
 *     - An AI Provenance target carrying the standard targetPath extension,
 *       e.g. target.extension[targetPath].valueString = "Procedure.followUp.text"
 *     - The AIconfidence extension on a nested element (including as a primitive
 *       extension, e.g. followUp._text.extension)
 *
 * The degree of involvement comes from Provenance.agent.type for the agents that
 * are AI Devices; whether a human reviewed the result comes from the agents that
 * are people. Model-Cards are found on the AI Device (modelCardDescription
 * extension or Device.note.text) or as a Provenance.entity DocumentReference.
 */

