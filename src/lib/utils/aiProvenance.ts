/**
 * The AI provenance to show for one resource, or undefined when it carries none
 * — in which case the caller renders nothing at all.
 */
export function getAiProvenance(
  resource: Resource | undefined,
  index: AiProvenanceIndex | undefined
): AiProvenanceSummary | undefined {
  if (!resource) return undefined;
  const idx = index ?? EMPTY_INDEX;
  const resolve: Resolver = (reference, container) => resolveReference(reference, idx.resourcesByKey, container);

  const provenances = provenancesFor(resource, idx);
  const securityLabelled = !!resource.meta?.security?.some(
    (c) => c.system === OBSERVATION_VALUE_CS && c.code === AIAST_CODE
  );
  const confidences = findConfidenceLabels(resource);
  const referencedDevice = aiDeviceReferencedBy(resource, resolve);

  if (provenances.length === 0 && !securityLabelled && confidences.length === 0 && !referencedDevice) {
    return undefined;
  }

  const resourceLevelSources: string[] = [];
  let resourceLevel = false;
  const elementLevel: AiElementLabel[] = [];

  if (securityLabelled) {
    resourceLevel = true;
    resourceLevelSources.push('The resource carries the "Artificial Intelligence asserted" security label.');
  }

  const seenPaths = new Set<string>();
  for (const provenance of provenances) {
    const targets = (provenance.target ?? []).filter((target) =>
      referenceKeys(target.reference).some((key) => resourceMatchesKey(resource, key))
    );
    for (const target of targets) {
      const targetPaths = extensionsOf(target)
        .filter((e) => e.url === TARGET_PATH_EXTENSION)
        .map((e) => e.valueString)
        .filter((p): p is string => !!p);
      if (targetPaths.length === 0) {
        resourceLevel = true;
        resourceLevelSources.push('An AI Provenance records this whole resource as its target.');
      }
      for (const path of targetPaths) {
        if (seenPaths.has(path)) continue;
        seenPaths.add(path);
        elementLevel.push({ path, source: 'provenance-target-path' });
      }
    }
  }

  let resourceConfidence: AiConfidence | undefined;
  for (const found of confidences) {
    if (!found.path) {
      resourceConfidence = found.confidence;
      resourceLevel = true;
      resourceLevelSources.push('An AI confidence is recorded for the resource as a whole.');
      continue;
    }
    const existing = elementLevel.find((e) => e.path === found.path);
    if (existing) {
      existing.confidence = found.confidence;
    } else {
      seenPaths.add(found.path);
      elementLevel.push({ path: found.path, source: 'element-confidence', confidence: found.confidence });
    }
  }

  if (referencedDevice && !resourceLevel && elementLevel.length === 0) {
    resourceLevel = true;
    resourceLevelSources.push('The resource names an AI Device as its source.');
  }

  // Agents, degree of involvement, and human review.
  const aiAgents: AiAgentInfo[] = [];
  const humanAgents: AiAgentInfo[] = [];
  const devices: AiDeviceInfo[] = [];
  const seenDeviceKeys = new Set<string>();
  let involvement: AiInvolvement = 'asserted';
  let humanReview: HumanReview = 'none';

  const addDevice = (device: Device, reference?: string) => {
    const key = reference ?? device.id ?? device.manufacturer ?? String(devices.length);
    if (seenDeviceKeys.has(key)) return;
    seenDeviceKeys.add(key);
    devices.push(deviceInfo(device, reference, resolve));
  };

  if (referencedDevice) addDevice(referencedDevice.device, referencedDevice.reference);

  const activities: string[] = [];
  const recorded: string[] = [];
  const inputPrompts: AiProvenanceSummary['inputPrompts'] = [];
  const provenanceModelCards: AiModelCard[] = [];

  for (const provenance of provenances) {
    const activity = conceptDisplay(provenance.activity);
    if (activity && !activities.includes(activity)) activities.push(activity);
    if (provenance.recorded && !recorded.includes(provenance.recorded)) recorded.push(provenance.recorded);

    for (const agent of provenance.agent ?? []) {
      const who = resolve(agent.who, provenance);
      const typeCode = agent.type?.coding?.find((c) => c.system === PARTICIPANT_TYPE_CS)?.code;
      const typeLabel = conceptDisplay(agent.type) ?? typeCode ?? 'Participant';
      if (isAiDevice(who)) {
        addDevice(who, agent.who?.reference);
        aiAgents.push({ typeLabel, display: agentDisplay(agent, who) });
        const mapped = typeCode ? AI_INVOLVEMENT_BY_PARTICIPANT_TYPE[typeCode] : undefined;
        if (mapped && AI_INVOLVEMENT_RANK[mapped] > AI_INVOLVEMENT_RANK[involvement]) involvement = mapped;
      } else if (isHumanAgent(agent, who)) {
        humanAgents.push({ typeLabel, display: agentDisplay(agent, who) });
        const mapped = (typeCode ? HUMAN_REVIEW_BY_PARTICIPANT_TYPE[typeCode] : undefined) ?? 'involved';
        if (HUMAN_REVIEW_RANK[mapped] > HUMAN_REVIEW_RANK[humanReview]) humanReview = mapped;
      }
    }

    for (const entity of provenance.entity ?? []) {
      const what = resolve(entity.what, provenance);
      if (isModelCardDocument(what)) {
        provenanceModelCards.push(modelCardFromDocument(what, 'provenance-entity', 'Referenced by the AI Provenance', resolve));
      } else if (isInputPromptDocument(what)) {
        const doc = what as DocumentReference;
        inputPrompts.push({
          title: doc.identifier?.[0]?.value,
          description: doc.description,
          text: doc.content?.map((c) => decodeTextAttachment(c.attachment)).find((t) => !!t)
        });
      }
    }
  }

  // Model-Cards found via the Provenance belong with the device they describe
  // when there is exactly one; otherwise they stand on their own. A producer
  // that both attaches the card to the Device and cites it from the Provenance
  // should not make the reader read it twice.
  if (provenanceModelCards.length > 0) {
    if (devices.length === 1) {
      const seen = new Set(devices[0].modelCards.map(modelCardKey));
      for (const card of provenanceModelCards) {
        if (seen.has(modelCardKey(card))) continue;
        seen.add(modelCardKey(card));
        devices[0].modelCards.push(card);
      }
    } else {
      devices.push({ display: 'AI system', kinds: [], modelCards: provenanceModelCards });
    }
  }

  const badgeLabel =
    involvement === 'generated'
      ? 'AI-generated'
      : involvement === 'contributed'
        ? 'AI-assisted'
        : involvement === 'reviewed'
          ? 'AI-reviewed'
          : 'AI-asserted';

  return {
    involvement,
    involvementLabel: AI_INVOLVEMENT_LABEL[involvement],
    involvementDetail: AI_INVOLVEMENT_DETAIL[involvement],
    humanReview,
    humanReviewLabel: HUMAN_REVIEW_LABEL[humanReview],
    humanReviewDetail: HUMAN_REVIEW_DETAIL[humanReview],
    resourceLevel,
    resourceLevelSources: Array.from(new Set(resourceLevelSources)),
    elementLevel,
    resourceConfidence,
    aiAgents,
    humanAgents,
    devices,
    activities,
    recorded: recorded.sort().reverse(),
    inputPrompts,
    badgeLabel
  };
}

function provenancesFor(resource: Resource, index: AiProvenanceIndex): Provenance[] {
  const found: Provenance[] = [];
  for (const key of resourceKeys(resource)) {
    for (const provenance of index.provenanceByTarget.get(key) ?? []) {
      if (!found.includes(provenance)) found.push(provenance);
    }
  }
  return found;
}

function resourceMatchesKey(resource: Resource, key: string): boolean {
  return resourceKeys(resource).includes(key);
}

function isHumanAgent(agent: ProvenanceAgent, who: Resource | undefined): boolean {
  if (who) return HUMAN_AGENT_TYPES.includes(who.resourceType);
  const reference = agent.who?.reference ?? '';
  return HUMAN_AGENT_TYPES.some((type) => reference.includes(`${type}/`));
}

function agentDisplay(agent: ProvenanceAgent, who: Resource | undefined): string {
  if (agent.who?.display) return agent.who.display;
  if (who?.resourceType === 'Device') {
    const device = who as Device;
    return device.deviceName?.find((n) => n.name)?.name ?? device.manufacturer ?? 'AI system';
  }
  if (who && 'name' in who) {
    const name = (who as { name?: unknown }).name;
    if (typeof name === 'string') return name;
    if (Array.isArray(name)) {
      const first = name[0] as { text?: string; given?: string[]; family?: string } | undefined;
      if (first?.text) return first.text;
      if (first) return [first.given?.join(' '), first.family].filter(Boolean).join(' ') || 'Unnamed';
    }
  }
  return agent.who?.reference ?? 'Unknown participant';
}
